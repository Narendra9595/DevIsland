import AppKit
import Observation
import SwiftUI

struct ClipItem: Identifiable, Equatable {
    enum Kind: String, CaseIterable {
        case text, link, code, color, image

        var symbol: String {
            switch self {
            case .text: "text.alignleft"
            case .link: "link"
            case .code: "chevron.left.forwardslash.chevron.right"
            case .color: "paintpalette.fill"
            case .image: "photo"
            }
        }
    }

    let id = UUID()
    let text: String
    var date: Date
    var isPinned = false
    /// Image data (images only), kept in memory.
    var image: Data?
    /// The app it was copied from.
    var app: String?

    var url: URL? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard image == nil, !trimmed.contains(" "), let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https" else { return nil }
        return url
    }

    var isLink: Bool { url != nil }

    var kind: Kind {
        if image != nil { return .image }
        if isLink { return .link }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if Color(hex: trimmed) != nil, trimmed.count <= 7 { return .color }
        let codeHints = ["{", "};", "=>", "func ", "def ", "import ", "const ", "let ", "return ", "</", "#include", "$ "]
        if codeHints.contains(where: trimmed.contains) && (trimmed.contains("\n") || trimmed.hasSuffix(";") || trimmed.contains("(")) {
            return .code
        }
        return .text
    }

    var preview: String {
        text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ")
    }
}

/// Opt-in clipboard history: text, links, code, colors and images. In memory only, cleared when turned off.
@MainActor
@Observable
final class ClipboardIntegration: Integration {
    let id = "clipboard"
    let name = "Clipboard History"
    let summary = "Recent copies (text, links, code, colors, images), kept in memory only. Skips passwords."
    let symbol = "doc.on.clipboard"
    let enabledByDefault = false

    private(set) var items: [ClipItem] = []

    @ObservationIgnored private var task: Task<Void, Never>?
    @ObservationIgnored private var lastChangeCount = 0
    private let maxItems = 60
    private let maxImages = 10
    private let maxBytes = 200_000
    private let maxImageBytes = 12_000_000
    /// Password managers mark secrets with these types. We never record them.
    private let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func start(publish: @escaping Publish) {
        lastChangeCount = NSPasteboard.general.changeCount
        task = Task { [weak self] in
            while !Task.isCancelled {
                self?.check()
                try? await Task.sleep(for: .seconds(1))
            }
        }
    }

    func stop() {
        task?.cancel()
        task = nil
        items.removeAll()
    }

    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let image = item.image {
            pasteboard.setData(image, forType: .tiff)
        } else {
            pasteboard.setString(item.text, forType: .string)
        }
        lastChangeCount = pasteboard.changeCount // don't record our own copy as new
        bump(item)
    }

    /// Whether DevIsland may press ⌘V for you (Accessibility permission).
    var canPaste: Bool { AXIsProcessTrusted() }

    /// Copies the item and pastes it into the app you're using, when allowed. Returns true if it pasted.
    @discardableResult
    func paste(_ item: ClipItem) -> Bool {
        copy(item)
        guard canPaste else { return false }
        let source = CGEventSource(stateID: .combinedSessionState)
        let key = CGKeyCode(9) // V
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
        return true
    }

    /// Shows macOS's Accessibility prompt so DevIsland can paste for you.
    func requestPastePermission() {
        let options = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
    }

    /// Removes everything except pinned items.
    func clear() {
        items.removeAll { !$0.isPinned }
    }

    /// Adds text to the top, keeping its pin if it was copied before.
    func record(_ text: String, app: String? = nil, at date: Date = .now) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.utf8.count <= maxBytes else { return }
        insert(ClipItem(text: text, date: date, app: app)) { $0.image == nil && $0.text == text }
    }

    func record(image: Data, size: CGSize, app: String? = nil, at date: Date = .now) {
        guard image.count <= maxImageBytes else { return }
        insert(ClipItem(text: "Image \(Int(size.width))×\(Int(size.height))", date: date, image: image, app: app)) { $0.image == image }
        let images = items.indices.filter { items[$0].image != nil && !items[$0].isPinned }
        if images.count > maxImages, let oldest = images.last { items.remove(at: oldest) }
    }

    private func insert(_ new: ClipItem, matching: (ClipItem) -> Bool) {
        if let index = items.firstIndex(where: matching) {
            var item = items.remove(at: index)
            item.date = new.date
            item.app = new.app ?? item.app
            items.insert(item, at: 0)
        } else {
            items.insert(new, at: 0)
        }
        let unpinned = items.indices.filter { !items[$0].isPinned }
        if unpinned.count > maxItems, let oldest = unpinned.last {
            items.remove(at: oldest)
        }
    }

    private func bump(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: index)
        moved.date = .now
        items.insert(moved, at: 0)
    }

    /// macOS has no "clipboard changed" notification, so we compare `changeCount`.
    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: skippedTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        if let text = pasteboard.string(forType: .string) {
            record(text, app: app)
        } else if let data = pasteboard.data(forType: .tiff) ?? pasteboard.data(forType: .png),
                  let image = NSImage(data: data) {
            record(image: data, size: image.size, app: app)
        }
    }
}
